// Finds every translation key used by client components ('use client' files) and writes
// lib/i18n/client-keys.ts, so the browser only receives the words it actually needs.
// Runs automatically before `npm run dev` and `npm run build`.
import { readFileSync, readdirSync, statSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const roots = ['app', 'components']
const files = []
const walk = (d) => {
  for (const n of readdirSync(d)) {
    const p = join(d, n)
    if (statSync(p).isDirectory()) walk(p)
    else if (/\.(tsx|ts)$/.test(n)) files.push(p)
  }
}
roots.forEach(walk)

const keys = new Set()
const prefixes = new Set(['nav.', 'common.', 'list.'])
for (const f of files) {
  const src = readFileSync(f, 'utf8')
  if (!/^\s*['"]use client['"]/.test(src)) continue
  for (const m of src.matchAll(/\bt\(\s*['"]([A-Za-z0-9_.& -]+)['"]/g)) keys.add(m[1])
  for (const m of src.matchAll(/\bt\(\s*`([A-Za-z0-9_]+\.)\$\{/g)) prefixes.add(m[1])
  // keys handed to t() through variables in client files are written as 'xx.yy' string literals nearby
  for (const m of src.matchAll(/['"]((?:la|lb|cl|adm|site|doc|msgs|mfa|auth|settings|shell|msg|acct|link|invite|folder|caseStatus|caseType|eventKind|priority|invStatus|sub|role|account)\.[A-Za-z0-9_.]+)['"]/g)) keys.add(m[1])
}
const out = `// GENERATED by scripts/client-keys.mjs. Do not edit by hand.
export const CLIENT_KEYS: readonly string[] = ${JSON.stringify([...keys].sort(), null, 0)}
export const CLIENT_PREFIXES: readonly string[] = ${JSON.stringify([...prefixes].sort())}
`
writeFileSync('lib/i18n/client-keys.ts', out)
console.log(`client i18n: ${keys.size} keys, ${prefixes.size} prefixes`)
