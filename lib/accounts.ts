import 'server-only'
import { createAdminClient } from '@/lib/supabase/admin'
import { getSiteUrl } from '@/lib/site-url'
import { mailConfigured, sendInviteEmail } from '@/lib/mail'
import { getI18n } from '@/lib/i18n'
import type { ActionState, UserRole } from '@/lib/types'

const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]+$/

type PersonInput =
  | { ok: true; email: string; fullName: string }
  | { ok: false; error: string; fields: Record<string, string> }

export async function readPerson(formData: FormData): Promise<PersonInput> {
  const { t } = await getI18n()
  const email = String(formData.get('email') ?? '').trim().toLowerCase()
  const fullName = String(formData.get('full_name') ?? '').trim().slice(0, 120)
  if (!fullName || !EMAIL_RE.test(email) || email.length > 254) {
    return { ok: false, error: t('common.error.invalidEmail'), fields: { email, full_name: fullName } }
  }
  return { ok: true, email, fullName }
}

// One-time "set your password" link. Generated by us, so it does not depend on
// Supabase's email sender or templates.
export async function buildSetupLink(email: string): Promise<{ link?: string; error?: string }> {
  const admin = createAdminClient()
  const { data, error } = await admin.auth.admin.generateLink({ type: 'recovery', email })
  const tokenHash = data?.properties?.hashed_token
  if (error || !tokenHash) return { error: error?.message ?? 'Could not generate the setup link.' }

  const site = await getSiteUrl()
  const params = new URLSearchParams({
    token_hash: tokenHash,
    type: 'recovery',
    next: '/auth/set-password',
  })
  return { link: `${site}/auth/confirm?${params.toString()}` }
}

async function findAuthUserIdByEmail(email: string): Promise<string | null> {
  const admin = createAdminClient()
  for (let page = 1; page <= 20; page++) {
    const { data, error } = await admin.auth.admin.listUsers({ page, perPage: 1000 })
    if (error) return null
    const hit = data.users.find((u) => u.email?.toLowerCase() === email)
    if (hit) return hit.id
    if (data.users.length < 1000) return null
  }
  return null
}

// Email the link when SMTP is configured (the inviter never sees the link, so they
// cannot use it to take over the account). Otherwise hand the link back to show in the UI.
type Delivery = { emailed: boolean; link?: string; note?: string }

async function deliverInvite(p: {
  email: string
  name: string
  invitedBy: string
}): Promise<Delivery> {
  const { link, error } = await buildSetupLink(p.email)
  if (!link) return { emailed: false, note: error }

  if (!mailConfigured()) return { emailed: false, link }

  const sent = await sendInviteEmail({ to: p.email, name: p.name, invitedBy: p.invitedBy, link })
  if (sent.ok) return { emailed: true }
  return { emailed: false, link, note: `The email could not be sent (${sent.error}).` }
}

export type CreateResult = ({ ok: true } & Delivery) | { ok: false; error: string }

// Creates auth user + profile + delivers the invite.
// Callers MUST have verified the caller's role first (requireRole).
export async function createAccount(input: {
  email: string
  fullName: string
  role: 'lawyer' | 'client' | 'junior'
  lawyerId?: string
  invitedBy: string
}): Promise<CreateResult & { userId?: string }> {
  const admin = createAdminClient()
  const { email, fullName, role, lawyerId } = input

  const { data: existingProfile } = await admin
    .from('profiles')
    .select('id')
    .eq('email', email)
    .maybeSingle()
  if (existingProfile) return { ok: false, error: (await getI18n()).t('acct.exists') }

  let userId: string
  let createdNow = true

  const { data, error } = await admin.auth.admin.createUser({
    email,
    email_confirm: true,
    user_metadata: { full_name: fullName },
  })

  if (data?.user) {
    userId = data.user.id
  } else {
    const exists = error?.code === 'email_exists' || /already.*registered/i.test(error?.message ?? '')
    if (!exists) return { ok: false, error: error?.message ?? 'Could not create the account.' }

    // Leftover auth user with no profile (earlier failed attempt): adopt it.
    const orphanId = await findAuthUserIdByEmail(email)
    if (!orphanId) return { ok: false, error: (await getI18n()).t('acct.exists') }
    userId = orphanId
    createdNow = false
  }

  const { error: profileError } = await admin.from('profiles').insert({
    id: userId,
    email,
    full_name: fullName,
    role,
    lawyer_id: role === 'client' || role === 'junior' ? lawyerId : null,
  })
  if (profileError) {
    if (createdNow) await admin.auth.admin.deleteUser(userId)
    return { ok: false, error: profileError.message }
  }

  const delivery = await deliverInvite({ email, name: fullName, invitedBy: input.invitedBy })
  return { ok: true, userId, ...delivery }
}

export async function createResultToState(
  result: CreateResult,
  email: string,
  fields: Record<string, string>,
  noun: string
): Promise<ActionState> {
  const { t } = await getI18n()
  if (!result.ok) return { error: result.error, fields }
  if (result.emailed) return { success: t('acct.createdEmailed', { noun, email }) }
  if (result.link) {
    return { success: t('acct.createdLink', { noun, note: result.note ?? t('acct.noEmail') }), link: result.link }
  }
  return { error: t('acct.noInvite', { note: result.note ?? '' }) }
}

// Re-sends (or re-issues) an invite, but ONLY for people who have not set a password yet.
// This can never be used to take over an account that is already in use.
export async function reissueInvite(
  userId: string,
  rules: { role: UserRole; lawyerId?: string },
  invitedBy: string
): Promise<ActionState> {
  const { t } = await getI18n()
  if (!userId) return { error: t('acct.missingUser') }

  const admin = createAdminClient()
  const { data: target } = await admin
    .from('profiles')
    .select('email, full_name, role, lawyer_id, password_set_at, is_active')
    .eq('id', userId)
    .maybeSingle()

  if (!target || target.role !== rules.role) return { error: t('acct.missingUser') }
  if (rules.lawyerId && target.lawyer_id !== rules.lawyerId) return { error: t('acct.missingUser') }
  if (!target.is_active) return { error: t('acct.suspended') }
  if (target.password_set_at) return { error: t('acct.alreadySet') }

  const d = await deliverInvite({
    email: target.email,
    name: target.full_name ?? target.email,
    invitedBy,
  })
  if (d.emailed) return { success: t('acct.sent', { email: target.email }) }
  if (d.link) return { success: d.note ?? t('acct.noEmail'), link: d.link }
  return { error: d.note ?? t('acct.linkFail') }
}
